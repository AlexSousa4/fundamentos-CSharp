
//Comparar valores - True (Verdadeiro) - False (falso)

// é possivel declarar 2 valores em 1 linha só
int a = 10, b = 11;

//Atribuição
// == Comparação de igualdade.

Console.WriteLine(a == b); //A é igual a B? False
Console.WriteLine(a != b); //A é diferente de B? True
Console.WriteLine(a > b); //A é Maior que B? False
Console.WriteLine(a < b); //A é Menor que B? True
Console.WriteLine(a >= b); //A é Menor ou Igual a B? True
Console.WriteLine(a <= b); //A é Maior ou Igual a B? False